// Obtener mazo inicial según equipo
export function getStartingDeck(team: 'athletic' | 'barcelona' | 'madrid'): Card[] {
  const deck: Card[] = [];

  if (team === 'athletic') {
    for (let i = 0; i < 4; i++) deck.push({ ...athleticCards[0], id: `strike_${i}` });
    for (let i = 0; i < 4; i++) deck.push({ ...athleticCards[1], id: `defend_${i}` });
    deck.push({ ...athleticCards[2], id: 'entrada_dura_0' });
    deck.push({ ...athleticCards[3], id: 'muro_rojiblanco_0' });
  } else if (team === 'barcelona') {
    for (let i = 0; i < 4; i++) deck.push({ ...barcelonaCards[0], id: `strike_${i}` });
    for (let i = 0; i < 4; i++) deck.push({ ...barcelonaCards[1], id: `defend_${i}` });
    deck.push({ ...barcelonaCards[2], id: 'tiki_taka_0' });
    deck.push({ ...barcelonaCards[3], id: 'toque_balon_0' });
  } else {
    for (let i = 0; i < 4; i++) deck.push({ ...madridCards[0], id: `strike_${i}` });
    for (let i = 0; i < 4; i++) deck.push({ ...madridCards[1], id: `defend_${i}` });
    deck.push({ ...madridCards[2], id: 'contraataque_0' });
    deck.push({ ...madridCards[3], id: 'galactico_0' });
  }

  return deck;
}
